  const count = (id: string) => (id === "atlas" ? geo.at.size : places.filter((p) => p[6] === id).length);

  const results = q.trim().length > 1 ? places.filter((p) => `${p[1]} ${p[2]} ${p[5]}`.toLowerCase().includes(q.trim().toLowerCase())).slice(0, 8) : [];
