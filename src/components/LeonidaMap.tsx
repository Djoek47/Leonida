  const [, force] = useState(0);
  const base = () => (document.querySelector("base") ? "" : "/");

  useEffect(() => { fetch(`${base()}gtadb/places.json`).then((r) => r.json()).then(setPlaces).catch(() => setPlaces([])); }, []);
